SELECT DATABASE();
USE txn_lab;
SHOW TABLES;
SELECT *
FROM account;

UPDATE account 
SET balance = 1000
WHERE id = 2;

SET SESSION TRANSACTION ISOLATION LEVEL
READ COMMITTED;

BEGIN;
UPDATE account
SET balance = balance - 100
WHERE id = 1;
COMMIT ;

SET SESSION TRANSACTION ISOLATION LEVEL
REPEATABLE READ;

BEGIN;
UPDATE account
SET balance = balance + 100
WHERE id = 1;
ROLLBACK ;

SELECT *
FROM account;
